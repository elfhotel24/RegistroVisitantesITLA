use AsistITLA

CREATE PROCEDURE SP_INSERTARAULA
    @ID_AULA VARCHAR(50),
    @EDIFICIO INT
AS
BEGIN
    INSERT INTO Aulas (IdAula, Edificio)
    VALUES (@ID_AULA, @EDIFICIO);
END


CREATE PROCEDURE SP_ACTUALIZARAULA
    @ID_ACTAULA VARCHAR(50),
    @ID_AULA VARCHAR(50),
    @EDIFICIO INT
AS
BEGIN
    UPDATE Aulas
    SET IdAula = @ID_AULA, Edificio = @EDIFICIO
    WHERE IdAula = @ID_ACTAULA;
END



CREATE PROCEDURE SP_BUSCARAULA
    @BUSCAR VARCHAR(50)
AS
BEGIN
    SELECT * FROM Aulas
    WHERE IdAula = @BUSCAR;
END


CREATE PROCEDURE SP_BUSCARAUPEDI
    @EDIFICIO INT
AS
BEGIN
    SELECT * FROM Aulas
    WHERE Edificio = @EDIFICIO;
END

CREATE PROCEDURE SP_ELIMINARAULA
    @ID_AULA VARCHAR(50)
AS
BEGIN
    DELETE FROM Aulas
    WHERE IdAula = @ID_AULA;
END


CREATE PROCEDURE SP_INSERTAREDIFICIO
    @ID_EDIFICIO INT,
    @DESCRIPCION VARCHAR(100)
AS
BEGIN
    INSERT INTO Edificios (DescripcionEdificio)
    VALUES (@DESCRIPCION);
END


CREATE PROCEDURE SP_EDITAREDIFICIOS
    @SELECCION INT,
    @NEW_ID INT,
    @DESCRIPCION VARCHAR(100)
AS
BEGIN
    UPDATE Edificios
    SET IdEdificio = @NEW_ID, DescripcionEdificio = @DESCRIPCION
    WHERE IdEdificio = @SELECCION;
END

CREATE PROCEDURE SP_LISTAREDIFICIOS
    @ID_EDIFICIO INT
AS
BEGIN
    SELECT * FROM Edificios
    WHERE IdEdificio = @ID_EDIFICIO;
END

CREATE PROCEDURE SP_INSERTARUSUARIO
    @NOMBRE VARCHAR(50),
    @APELLIDO VARCHAR(50),
    @FECHANACIMIENTO DATE,
    @TIPOUSUARIO VARCHAR(20),
    @USERPASSWORD VARCHAR(100)
AS
BEGIN
    INSERT INTO Usuarios (Nombre, Apellido, FechaNacimiento, TipoUsuario, Password)
    VALUES (@NOMBRE, @APELLIDO, @FECHANACIMIENTO, @TIPOUSUARIO, @USERPASSWORD);
END

CREATE PROCEDURE SP_ACTUALIZARUSUARIO
    @CODUSUARIO VARCHAR(50),
    @NOMBRE VARCHAR(50),
    @APELLIDO VARCHAR(50),
    @FECHANACIMIENTO DATE,
    @TIPOUSUARIO VARCHAR(20),
    @USERPASSWORD VARCHAR(100)
AS
BEGIN
    UPDATE Usuarios
    SET Nombre = @NOMBRE, Apellido = @APELLIDO, FechaNacimiento = @FECHANACIMIENTO, TipoUsuario = @TIPOUSUARIO, Password = @USERPASSWORD
    WHERE CodUsuario = @CODUSUARIO;
END


CREATE PROCEDURE SP_ELIMINARUSUARIO
    @CODUSUARIO VARCHAR(50)
AS
BEGIN
    DELETE FROM Usuarios
    WHERE CodUsuario = @CODUSUARIO;
END


CREATE PROCEDURE SP_BUSCARUSUARIOPPORNOMBRE
    @BUSCAR VARCHAR(50)
AS
BEGIN
    SELECT * FROM Usuarios
    WHERE Nombre LIKE '%' + @BUSCAR + '%';
END



CREATE PROCEDURE SP_BUSCARUSUARIO
    @CODUSUARIO VARCHAR(50)
AS
BEGIN
    SELECT * FROM Usuarios
    WHERE CodUsuario = @CODUSUARIO;
END



CREATE PROCEDURE SP_LOGIN
    @CODUSUARIO VARCHAR(50),
    @USERPASSWORD VARCHAR(100)
AS
BEGIN
    SELECT * FROM Usuarios
    WHERE CodUsuario = @CODUSUARIO AND Password = @USERPASSWORD;
END



CREATE PROCEDURE SP_INSERTARVISITANTE
    @NOMBRE VARCHAR(50),
    @APELLIDO VARCHAR(50),
    @CARRERA VARCHAR(50),
    @EDIFICIO INT,
    @HORASALIDA DATETIME,
    @MOTIVOVISITA VARCHAR(255),
    @ID_AULA VARCHAR(50)
AS
BEGIN
    INSERT INTO Visitantes (Nombre, Apellido, Carrera, Edificio, HoraSalida, MotivoVisita, IdAula)
    VALUES (@NOMBRE, @APELLIDO, @CARRERA, @EDIFICIO, @HORASALIDA, @MOTIVOVISITA, @ID_AULA);
END



CREATE PROCEDURE SP_BUSCARVISITANTE
    @BUSCAR VARCHAR(50)
AS
BEGIN
    SELECT * FROM Visitantes
    WHERE Nombre LIKE '%' + @BUSCAR + '%';
END



CREATE PROCEDURE SP_BUSCARVISPOREDIFICIO
    @BUSCAR INT
AS
BEGIN
    SELECT * FROM Visitantes
    WHERE Edificio = @BUSCAR;
END